'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const site=process.argv[2]||path.join(__dirname,'..','site');
const html=fs.readFileSync(path.join(site,'index.html'),'utf8');
const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(x=>x[1]);
const app=scripts.find(x=>x.includes('Mau-Mau 2.0 — aplicação e interface.'));
assert(app,'Aplicacao offline ausente');
const rosterMatch=app.match(/const ALL_BOTS=(\[[^;]+\]);/);
assert(rosterMatch,'Catalogo de bots ausente');
const ALL_BOTS=JSON.parse(rosterMatch[1]);
assert(ALL_BOTS.length>=10);
assert(app.includes('portraitHTML(p.portraitName||p.name)'),'Mesa ainda usa retrato generico');

const helperStart=app.indexOf('const onlineBotPortraitCache=new Map();');
const helperEnd=app.indexOf('window.__tavOriginalOnline={',helperStart);
assert(helperStart>0&&helperEnd>helperStart,'Mapeamento de retratos online nao encontrado');
const ctx=vm.createContext({ALL_BOTS,Map,Set,String});
vm.runInContext(app.slice(helperStart,helperEnd),ctx);
const assign=vm.runInContext('onlineBotPortraits',ctx);
const members=Array.from({length:9},(_,i)=>({id:'bot-'+String(i).padStart(2,'0'),name:'Forasteiro bot '+i,isBot:true}));
const ordered=members.map(m=>({id:m.id}));
const first=assign(ordered,members);
assert.equal(first.size,9,'Nao encontrou os nove bots');
const portraits=members.map(m=>first.get(m.id));
assert(portraits.every(x=>ALL_BOTS.includes(x)),'Usou imagem fora do elenco');
assert.equal(new Set(portraits).size,9,'Retratos repetidos no online');
const reversed=assign(ordered.slice().reverse(),members);
assert.deepEqual(members.map(m=>reversed.get(m.id)),portraits,'Retratos variam com perspectiva dos jogadores');
members[0].name='Baldric';
const named=assign(ordered,members);
assert.equal(named.get('bot-00'),'Baldric','Bot conhecido nao usa seu proprio retrato');
assert.equal(new Set(members.map(m=>named.get(m.id))).size,9,'Retrato repetido quando ha bot conhecido');

const start=app.indexOf('const replayBots=');
const end=app.indexOf('try{localStorage.setItem(',start);
assert(start>0&&end>start,'Logica da revanche offline ausente');
const fn=vm.runInNewContext('(function(count,replay,ui,ALL_BOTS,shuffle){'+app.slice(start,end)+';return bots;})');
const names=['Eu','Baldric','Cedric','Aldren','Dorian','Godric'];
const ui={game:{state:{players:names.map(name=>({name}))}},seenBotNames:names.slice(1)};
const shuffle=arr=>arr.slice().reverse();
const revenge=fn(6,true,ui,ALL_BOTS,shuffle);
assert.deepEqual(revenge,names.slice(1),'Revanche trocou adversarios');
assert.deepEqual(ui.seenBotNames,names.slice(1));
const newMatch=fn(6,false,ui,ALL_BOTS,shuffle);
assert.equal(newMatch.length,5,'Partida nova sem cinco bots');
assert.notDeepEqual(newMatch,names.slice(1),'Partida nova deixou de variar adversarios');
console.log('BOT_IDENTITY_REGRESSION_OK: 9 retratos distintos, bots conhecidos e revanche offline preservada');
