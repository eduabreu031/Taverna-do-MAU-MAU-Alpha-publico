'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const site=process.argv[2]||path.join(root,'site');
const html=fs.readFileSync(path.join(site,'index.html'),'utf8');
assert(html.includes('id="tav-offline-pause-v55-style"'),'CSS da pausa não foi instalado');
const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(x=>x[1]);
for(const s of scripts)if(s.trim())new vm.Script(s);
const core=scripts.find(x=>x.includes('Mau-Mau 2.0 — aplicação e interface.'));
const cronicas=scripts.find(x=>x.includes('Crônicas da Taverna — Fase 3C'));
assert(core&&cronicas);
assert(core.includes('function tavOfflinePause(mode='),'Pausa offline não integrada ao motor');
assert(core.includes("function schedule(phase='normal',resume=null)"),'Agendador não recebe duração restante');
assert(core.includes('pauseSchedulers(); // invalida callbacks'),'Relógios não interrompidos');
assert(core.includes('ui.clockCarry={ms:snapshot.humanMs}'),'Relógio humano não restaurado');
assert(core.includes('const botMs=resume?.botMs??Core.RULES.humanMainMs'),'Tempo dos bots não restaurado');
assert(core.includes('const incidentMs=resume?.incidentMs??Core.RULES.accusationMs'),'OPA!!! não restaurado');
assert(core.includes("function humanTurn(s){return !ui.offlinePaused"),'Jogadas humanas não bloqueadas');
assert(core.includes('scene.inert=true'),'Mesa não bloqueada durante a pausa');
assert(core.includes('tav-offline-pause-mark')&&core.includes('<svg viewBox="0 0 24 24"'),'Ícone vetorial real da pausa ausente');
assert(!core.includes('Ⅱ</div>'),'Numeral romano indevido voltou à pausa');
assert(html.includes('id="tav-hud-design-v56-style"'),'Contrato visual v56 não foi montado');
assert(core.includes('tavOfflineReset();arautoStop()'),'Pausa não limpa ao sair');
assert(core.includes('ui.game.state.phase===\'playing\''),'Retorno não filtra o encerramento');
assert(cronicas.includes("install('#sceneGame','.game-header .utility-toolbar')"),'Botão de conquistas não está no HUD');
assert(cronicas.includes('holdForCronicas'),'Abrir conquistas não congela o relógio offline');
assert(cronicas.includes('releaseCronicas'),'Fechar conquistas não retoma o relógio offline');
const css=fs.readFileSync(path.join(root,'qa','offline-pause-ui-v55.css'),'utf8');
assert(css.includes('max-width:760px')&&css.includes('clamp(27px,8.5vw,36px)'),'Barra móvel não cabe com nove botões');
const releases=JSON.parse(fs.readFileSync(path.join(root,'qa','alpha-releases.json'),'utf8'));
assert.equal(releases.current,'alpha-0.5.0.56');
const sw=fs.readFileSync(path.join(site,'sw.js'),'utf8');
assert(sw.includes('taverna-pwa-alpha-0.5.0.55'),'Cache PWA desatualizado');
console.log('OFFLINE_PAUSE_V55_OK: timers, IA, OPA, HUD, conquistas e versionamento');
